'use strict';
// Owner tool: recomputes the licence fingerprints and writes them to core/seal.js.
// Run it only after you changed a protected file on purpose:  npm run seal
const fs = require('node:fs');
const path = require('node:path');
const { fingerprints } = require('../core/guard');

const out = fingerprints();
const body = `'use strict';\n// Generated by tools/seal.js. Do not edit by hand.\nmodule.exports = ${JSON.stringify(out, null, 2)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'core', 'seal.js'), body);
console.log('Sealed:', Object.keys(out).join(', '));
